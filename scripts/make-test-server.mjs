// Builds a throwaway Minecraft server directory so addon syntax can be tested
// without owning a server.
//
// The language server decides which addons exist by reading the JARs in a
// `plugins/` folder — their `plugin.yml` or `paper-plugin.yml`, nothing more.
// So a directory of stub JARs carrying only that manifest is indistinguishable
// from the real thing as far as syntax loading is concerned, and it is the only
// way to see `examples/sample-project/addons.sk` light up if you do not happen
// to run a server with seven addons installed.
//
// It is *not* a substitute for testing against a real server: it proves the
// syntax loads and hovers, not that any of these plugins would actually run.
//
//   node scripts/make-test-server.mjs
//
// then point the language server at the directory it prints.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { writeJar } from './lib/make-jar.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const server = join(root, 'examples', 'sample-project', 'test-server');
const plugins = join(server, 'plugins');

// Every addon `addons.sk` demonstrates, at a version whose syntax the catalog
// publishes. The name must match SkriptHub's spelling — that string is what the
// server matches against, and a typo simply means the addon is "not installed".
const ADDONS = [
  { name: 'SkBee', version: '3.9.2', paper: true },
  { name: 'skript-reflect', version: '2.5.1' },
  { name: 'SkQuery', version: '4.1.10' },
  { name: 'TuSKe', version: '1.8.5' },
  { name: 'skRayFall', version: '1.9.28' },
  { name: 'MundoSK', version: '1.9.19' },
  { name: 'Lusk', version: '1.3.2', paper: true },
];

// Not an addon. Included because "found a JAR" and "found an addon" are
// different questions, and a server without at least one ordinary plugin never
// exercises the difference.
const PLAIN = { name: 'LuckPerms', version: '5.5.50', addon: false };

// Skript itself. Without it the server cannot tell which version the project
// targets, and every `since` check falls back to assuming syntax is available.
const SKRIPT = { name: 'Skript', version: '2.16.1', addon: false };

rmSync(server, { recursive: true, force: true });
mkdirSync(plugins, { recursive: true });

// A plugin counts as a Skript addon only if it *declares* a dependency on
// Skript. That is the whole detection rule, and it is why the first version of
// these stubs — which omitted it — was correctly reported as eight ordinary
// plugins and zero addons.
const manifest = ({ name, version, paper, addon = true }) => {
  const head = [
    `name: ${name}`,
    `version: ${version}`,
    `main: com.example.${name.replace(/[^A-Za-z0-9]/g, '')}.Plugin`,
    'api-version: "1.21"',
  ];
  if (!addon) {
    return [...head, ''].join('\n');
  }
  // Paper nests its dependencies; Bukkit uses a flat list. Both are in the
  // wild, and the detector has to read either.
  return paper
    ? [...head, 'dependencies:', '  server:', '    Skript:', '      required: true', ''].join('\n')
    : [...head, 'depend: [Skript]', ''].join('\n');
};

for (const addon of [...ADDONS, PLAIN, SKRIPT]) {
  // SkBee and Lusk ship `paper-plugin.yml` and no `plugin.yml` at all, which is
  // the case a plugin.yml-only detector silently misses.
  const file = addon.paper ? 'paper-plugin.yml' : 'plugin.yml';
  writeJar(join(plugins, `${addon.name}-${addon.version}.jar`), {
    [file]: manifest(addon),
  });
}

// A server.properties makes the directory look like what it claims to be, and
// costs nothing.
writeFileSync(
  join(server, 'server.properties'),
  '# Generated by scripts/make-test-server.mjs — not a real server.\nlevel-name=world\n',
);

writeFileSync(
  join(server, 'README.md'),
  [
    '# Generated test server',
    '',
    'Created by `node scripts/make-test-server.mjs`, and gitignored — delete it',
    'freely, it is rebuilt in under a second.',
    '',
    'The JARs here contain a manifest and nothing else. They exist so the',
    'language server detects the addons and loads their syntax; none of them',
    'would run on an actual server.',
    '',
    '## Use it',
    '',
    'Point the language server at this directory:',
    '',
    '```jsonc',
    '"lsp": {',
    '  "skript-lsp": {',
    '    "initialization_options": {',
    `      "serverPath": ${JSON.stringify(server.replace(/\\/g, '/'))}`,
    '    }',
    '  }',
    '}',
    '```',
    '',
    'Restart the language server, then open `examples/sample-project/addons.sk`.',
    'Every line under a `# === Addon ===` heading should now hover and colour.',
    'Without this, those lines stay plain — which is correct behaviour, not a',
    'bug: the server never guesses at syntax for an addon you do not have.',
    '',
  ].join('\n'),
);

console.log(
  `Wrote ${ADDONS.length} addon stubs, Skript itself, and one ordinary plugin to:`,
);
console.log(`  ${plugins}`);
console.log('');
console.log('Point the language server at the server directory:');
console.log('');
console.log('  "lsp": { "skript-lsp": { "initialization_options": {');
console.log(`    "serverPath": ${JSON.stringify(server.replace(/\\/g, '/'))}`);
console.log('  } } }');
console.log('');
console.log('Then restart the language server and open addons.sk.');
